	/**
	 * Get mime type according to file extension
	 * @param string $filename file name
	 * @return string
	 */
	static public function getFileMime($filename)
	{
		$ext = Core_File::getExtension($filename);

		return isset(self::$_mimes[$ext])
			? self::$_mimes[$ext]
			: 'text/plain';
	}
